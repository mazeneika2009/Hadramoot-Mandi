-- Hadramout House of Mandi - initial PostgreSQL / Supabase schema.
--
-- Apply this migration with `npm run db:init` (uses POSTGRES_URL_NON_POOLING)
-- or paste it into the Supabase SQL Editor. The application itself only uses
-- the Supabase REST client and the service-role key.

-- ---------------------------------------------------------------------------
-- Enums
-- ---------------------------------------------------------------------------

do $$
begin
  create type public.user_role as enum (
    'customer', 'admin', 'kitchen', 'cashier', 'delivery'
  );
exception
  when duplicate_object then null;
end
$$;

do $$
begin
  create type public.order_payment_status as enum (
    'PENDING', 'PAID', 'FAILED', 'REFUNDED'
  );
exception
  when duplicate_object then null;
end
$$;

do $$
begin
  create type public.order_lifecycle_status as enum (
    'PENDING', 'PREPARING', 'READY', 'OUT_FOR_DELIVERY', 'DELIVERED', 'CANCELLED'
  );
exception
  when duplicate_object then null;
end
$$;

do $$
begin
  create type public.order_payment_method as enum ('ONLINE', 'CASH');
exception
  when duplicate_object then null;
end
$$;

do $$
begin
  create type public.reservation_status as enum (
    'PENDING', 'CONFIRMED', 'CANCELLED', 'COMPLETED'
  );
exception
  when duplicate_object then null;
end
$$;

-- ---------------------------------------------------------------------------
-- Tables
-- ---------------------------------------------------------------------------

create table if not exists public.users (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null,
  password_hash text not null,
  phone text,
  role public.user_role not null default 'customer',
  is_approved boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint users_email_key unique (email)
);

create table if not exists public.menu_items (
  id bigint generated by default as identity primary key,
  name text not null,
  name_en text,
  description text,
  description_en text,
  price numeric(10, 2) not null check (price >= 0),
  category text not null,
  image_url text,
  is_available boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  user_id bigint not null,
  total_amount numeric(10, 2) not null check (total_amount >= 0),
  delivery_address text not null,
  payment_status public.order_payment_status not null default 'PENDING',
  order_status public.order_lifecycle_status not null default 'PENDING',
  payment_id text,
  payment_url text,
  payment_method public.order_payment_method not null default 'ONLINE',
  delivery_user_id bigint,
  dispatched_at timestamptz,
  delivered_at timestamptz,
  cash_received numeric(10, 2),
  cash_change numeric(10, 2),
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint orders_user_id_fkey
    foreign key (user_id) references public.users (id) on delete cascade,
  constraint orders_delivery_user_id_fkey
    foreign key (delivery_user_id) references public.users (id) on delete set null
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null,
  menu_item_id bigint not null,
  quantity integer not null default 1 check (quantity > 0),
  price_at_purchase numeric(10, 2) not null check (price_at_purchase >= 0),
  created_at timestamptz not null default now(),
  constraint order_items_order_id_fkey
    foreign key (order_id) references public.orders (id) on delete cascade,
  constraint order_items_menu_item_id_fkey
    foreign key (menu_item_id) references public.menu_items (id) on delete restrict
);

create table if not exists public.reservations (
  id bigint generated by default as identity primary key,
  user_id bigint,
  name text not null,
  phone text not null,
  email text,
  "date" date not null,
  "time" time not null,
  guests integer not null default 1 check (guests > 0),
  status public.reservation_status not null default 'PENDING',
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint reservations_user_id_fkey
    foreign key (user_id) references public.users (id) on delete set null
);

