-- ---------------------------------------------------------------------------
-- Atomic order creation
-- ---------------------------------------------------------------------------

-- The payment method is accepted as text and cast inside the function so
-- PostgREST does not need to resolve the custom enum during RPC dispatch.
drop function if exists public.create_order_with_items(
  bigint, numeric, text, public.order_payment_method, text, jsonb
);

create or replace function public.create_order_with_items(
  p_user_id bigint,
  p_total_amount numeric,
  p_delivery_address text,
  p_payment_method text,
  p_notes text,
  p_items jsonb
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order_id bigint;
begin
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'Order must contain at least one item' using errcode = '22023';
  end if;

  insert into public.orders (
    user_id,
    total_amount,
    delivery_address,
    payment_method,
    notes
  )
  values (
    p_user_id,
    p_total_amount,
    p_delivery_address,
    p_payment_method::public.order_payment_method,
    p_notes
  )
  returning id into v_order_id;

  insert into public.order_items (
    order_id,
    menu_item_id,
    quantity,
    price_at_purchase
  )
  select
    v_order_id,
    (item ->> 'menu_item_id')::bigint,
    (item ->> 'quantity')::integer,
    (item ->> 'price_at_purchase')::numeric
  from jsonb_array_elements(p_items) as item;

  return v_order_id;
end;
$$;

-- ---------------------------------------------------------------------------
-- Admin dashboard statistics
-- ---------------------------------------------------------------------------

create or replace function public.get_order_stats()
returns table (
  total_orders bigint,
  pending_orders bigint,
  preparing_orders bigint,
  out_for_delivery_orders bigint,
  delivered_orders bigint,
  cancelled_orders bigint,
  total_revenue numeric
)
language sql
stable
security definer
set search_path = public
as $$
  select
    count(*)::bigint as total_orders,
    count(*) filter (where o.order_status = 'PENDING')::bigint as pending_orders,
    count(*) filter (where o.order_status = 'PREPARING')::bigint as preparing_orders,
    count(*) filter (where o.order_status = 'OUT_FOR_DELIVERY')::bigint as out_for_delivery_orders,
    count(*) filter (where o.order_status = 'DELIVERED')::bigint as delivered_orders,
    count(*) filter (where o.order_status = 'CANCELLED')::bigint as cancelled_orders,
    coalesce(
      sum(o.total_amount) filter (where o.payment_status = 'PAID'),
      0
    )::numeric as total_revenue
  from public.orders o;
$$;

-- ---------------------------------------------------------------------------
-- Row Level Security
--
-- The API uses the service-role key, which bypasses RLS. No policies are
-- created, so anon/authenticated keys cannot touch these tables directly.
-- ---------------------------------------------------------------------------

alter table public.users enable row level security;
alter table public.menu_items enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;
alter table public.reservations enable row level security;

-- ---------------------------------------------------------------------------
-- Grants
-- ---------------------------------------------------------------------------

grant select, insert, update, delete
  on public.users, public.menu_items, public.orders, public.order_items, public.reservations
  to service_role;

grant usage, select
  on all sequences in schema public
  to service_role;

revoke all on function public.create_order_with_items(
  bigint, numeric, text, text, text, jsonb
) from public, anon, authenticated;
grant execute on function public.create_order_with_items(
  bigint, numeric, text, text, text, jsonb
) to service_role;

revoke all on function public.get_order_stats() from public, anon, authenticated;
grant execute on function public.get_order_stats() to service_role;

-- Ask PostgREST/Supabase to refresh its schema cache so the new tables,
-- relationships and RPC functions are available immediately.
notify pgrst, 'reload schema';
